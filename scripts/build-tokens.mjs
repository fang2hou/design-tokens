import StyleDictionary from "style-dictionary";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const dist = join(root, "dist");
mkdirSync(dist, { recursive: true });

const primitives = [
  "tokens/primitives/color.json",
  "tokens/primitives/typography.json",
  "tokens/primitives/radius.json",
  "tokens/primitives/spacing.json",
];

async function buildCss(includeGlobs, sourceGlobs, selector, destination, filterPath = "") {
  const sd = new StyleDictionary({
    include: includeGlobs,
    source: sourceGlobs,
    platforms: {
      css: {
        transformGroup: "css",
        buildPath: "dist/",
        files: [
          {
            destination,
            format: "css/variables",
            filter: (token) => (filterPath ? token.filePath?.includes(filterPath) : true),
            options: { selector, outputReferences: true },
          },
        ],
      },
    },
  });
  await sd.buildAllPlatforms();
}

function collectSiteData() {
  const load = (path) => JSON.parse(readFileSync(join(root, path), "utf8"));
  const primitives = load("tokens/primitives/color.json");
  const light = load("tokens/semantic/color.light.json");
  const dark = load("tokens/semantic/color.dark.json");
  const resolve = (value) => {
    if (typeof value === "string" && value.startsWith("{")) {
      let node = primitives;
      for (const segment of value.slice(1, -1).split(".")) {
        node = node[segment];
      }
      return node?.$value ?? "";
    }
    return value;
  };
  const semantic = Object.keys(light)
    .filter((key) => !key.startsWith("$"))
    .map((key) => ({
      name: `--${key}`,
      light: resolve(light[key].$value),
      dark: resolve(dark[key].$value),
    }));
  const palette = { light: [], dark: [] };
  for (const mode of ["light", "dark"]) {
    for (const [key, entry] of Object.entries(primitives.palette[mode])) {
      if (key.startsWith("$")) continue;
      palette[mode].push({ name: `--palette-${mode}-${key}`, value: entry.$value });
    }
  }
  return { semantic, palette };
}

function readTokenFiles() {
  const load = (path) => JSON.parse(readFileSync(join(root, path), "utf8"));
  return {
    semanticLight: load("tokens/semantic/color.light.json"),
    semanticDark: load("tokens/semantic/color.dark.json"),
    typography: load("tokens/primitives/typography.json"),
    radius: load("tokens/primitives/radius.json"),
    spacing: load("tokens/primitives/spacing.json"),
  };
}

function tailwindAdapter(tokens) {
  const lines = [];
  const walk = (node, path, colorPrefix) => {
    for (const [key, value] of Object.entries(node)) {
      if (key.startsWith("$")) continue;
      const name = path.length === 0 ? key : `${path}-${key}`;
      if ("$value" in value) {
        const prefix = colorPrefix ? "color-" : "";
        lines.push(`  --${prefix}${name}: var(--${name});`);
      } else {
        walk(value, name, colorPrefix);
      }
    }
  };
  walk(tokens.semanticLight, "", true);
  walk(tokens.typography, "", false);
  walk(tokens.radius, "", false);
  lines.push("  --spacing: var(--spacing-unit);");
  return `@theme inline {\n${lines.join("\n")}\n}\n`;
}

async function main() {
  await buildCss(primitives, ["tokens/semantic/color.light.json"], ":root", "tokens.light.css");
  await buildCss(
    primitives,
    ["tokens/semantic/color.dark.json"],
    ".dark",
    "tokens.dark.css",
    "color.dark.json",
  );

  const lightCss = readFileSync(join(dist, "tokens.light.css"), "utf8");
  const darkCss = readFileSync(join(dist, "tokens.dark.css"), "utf8");
  const banner = "/* Generated by scripts/build-tokens.mjs from DTCG sources. Do not edit. */\n";
  writeFileSync(join(dist, "tokens.css"), `${banner}${lightCss}\n${darkCss}`);

  const tokens = readTokenFiles();
  writeFileSync(join(dist, "tailwind.css"), `${banner}${tailwindAdapter(tokens)}`);

  writeFileSync(join(dist, "tokens.flat.json"), `${JSON.stringify(collectSiteData(), null, 2)}\n`);
  for (const name of ["tokens.light.css", "tokens.dark.css"]) {
    rmSync(join(dist, name));
  }
}

await main();
